const enc = (value: any): string => encodeURIComponent(String(value ?? ''));

const need = (...keys: string[]) => (args: ToolArgs) => {
  requireArgs(args, keys);
  return args;
};

function pageQuery(args: ToolArgs): Record<string, any> {
  return { page: args.page, size: args.size };
}

function withParams(args: ToolArgs, base: Record<string, any>, params: any = args.params): Record<string, any> {
  return params && typeof params === 'object' && !Array.isArray(params) ? { ...base, ...params } : base;
}

